package com.oopnv70.uilab.glass

/**
 * 液态玻璃的**总开关**（UI 层面的熔断）。
 *
 * ---------------------------------------------------------------------------
 * 为什么要有这个开关（2026-09-15）
 * ---------------------------------------------------------------------------
 * 液态玻璃经历了自研 shader → 第三方库（QWEA0 v2.0.10）两轮攻坚，结论是：
 *
 *   - 自研版：黑屏 / 闪退 / 白板 / 背景源选错，反复不收敛；
 *   - 第三方库：在 Compose 宿主下没有可用的背景源 ——
 *       · 指 AndroidComposeView（祖先）→ 每次启动必崩
 *           IllegalStateException: Recording currently in progress
 *       · 不指（回退 AndroidViewsHandler 空壳父级）→ 捕获空白 → 发黑
 *     两条路都走不通，而 App 的全部内容都画在同一棵 AndroidComposeView 里，
 *     不存在「与玻璃同级、又不包含玻璃」的普通 View 可作为背景源。
 *
 * 所以**暂停**液态玻璃这条线，但**不删除任何代码、不改动任何结构**：
 * 组件、枚举、设置项、渲染实现全部原样保留，只是不再被渲染。
 *
 * ---------------------------------------------------------------------------
 * 如何使用
 * ---------------------------------------------------------------------------
 * 所有「是否走玻璃分支」的判断都必须经过 [enabled]：
 *
 *   val glassMode = GlassFeature.enabled && settings.themeStyle == ThemeStyle.LIQUID_GLASS
 *
 * 想恢复功能时，把 [enabled] 改回 `true` 即可 —— 一处开关，全局生效，
 * 不需要再逐个文件去找 `== ThemeStyle.LIQUID_GLASS`。
 *
 * 注意：置为 `true` 之前必须先解决背景源问题，否则会立刻回到
 * 「必崩 or 必黑」二选一的状态（见上）。
 */
object GlassFeature {

    /**
     * 液态玻璃是否启用。
     *
     * `false` = UI 层面完全屏蔽：即使用户在设置里选了「液态玻璃」，
     *           界面也按普通实心样式渲染，不产生任何玻璃绘制。
     */
    const val enabled: Boolean = false
}
