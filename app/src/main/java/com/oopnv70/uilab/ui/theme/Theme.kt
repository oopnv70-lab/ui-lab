/**
 * 应用主题。
 *
 * @param darkTheme 是否使用深色主题（默认跟随系统）。
 * @param dynamicColor 是否启用动态取色（Monet，Android 12+ 跟随壁纸）。
 *        注意：开启后 Color.kt 中的基准色会被系统根据壁纸生成的配色覆盖；
 *        若想看本项目自带的「更亮」基准色，把此参数设为 false。
 */
@Composable
fun UiLabTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // ⚠️ 已关闭动态取色。
    // 原因：动态取色（Monet）会用「壁纸生成的配色」覆盖本文件的基准色，
    // 导致 Color.kt 里精心调过的「更亮」配色完全失效。
    // 要恢复动态取色，把这里改成 true 即可。
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        // Android 12（API 31）及以上支持动态取色
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkScheme
        else -> LightScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = Shapes,
        content = content
    )
}